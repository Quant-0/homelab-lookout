const { chromium } = require('playwright');
const S = process.env.SCREENSHOT_DIR || require('node:os').tmpdir();
const B = process.env.BASE_URL || 'http://127.0.0.1:18080';
const problems = [];
const check = (c, m) => { console.log(`${c ? 'PASS' : 'FAIL'}  ${m}`); if (!c) problems.push(m); };
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
  page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && problems.push(`console: ${m.text()}`));
  page.on('pageerror', (e) => problems.push(`pageerror: ${e.message}`));
  page.on('dialog', (d) => d.accept());
  await page.goto(B + '/login');
  await page.fill('#username', 'admin');
  await page.fill('#password', 'correct horse battery');
  await page.click('button[type=submit]');
  await page.waitForURL(B + '/');
  await page.goto(B + '/admin');
  await page.waitForSelector('#tab-devices:not([hidden])');
  check(page.url().endsWith('#devices'), 'admin opens on the Devices tab');

  const conn = (i) => page.locator('#conn-list .conn-card').nth(i);
  const fill = async (card, label, value) => card.locator('label', { hasText: label }).locator('input').first().fill(value);

  // --- Add device from the catalog: a Dell PowerEdge R740 called Orion, with Redfish + Proxmox ---
  await page.click('#device-new');
  await page.waitForSelector('dialog.drawer[open] .cat-brand');
  check(await page.locator('.cat-brand').count() >= 18, `catalog step 1: ${await page.locator('.cat-brand').count()} brands`);
  await page.click('.cat-brand:has-text("UniFi")');
  await page.waitForSelector('.cat-type');
  const uniTypes = await page.$$eval('.cat-type b', (n) => n.map((x) => x.textContent));
  check(['Gateways & routers', 'Switches', 'Access points', 'NAS & recorders', 'Cameras', 'UPS', 'Power'].every((t) => uniTypes.includes(t)), `step 2, UniFi's types: ${uniTypes.join(', ')}`);
  await page.click('.cat-type:has-text("Access points")');
  await page.waitForSelector('.cat-model');
  check(await page.locator('.cat-model').count() >= 15 && await page.locator('.cat-model .product-shape').count() === await page.locator('.cat-model').count(), 'step 3: every UniFi access point, drawn as its shape');
  await page.click('.cat-crumbs button:has-text("UniFi")');
  await page.click('.cat-type:has-text("Switches")');
  await page.waitForSelector('.cat-model');
  check(/48 ports \(PoE\) · 4 SFP/.test(await page.textContent('.cat-model:has-text("Pro Max 48 PoE")')) && await page.locator('.cat-model:has-text("Pro Max 48 PoE") .rack-item .port').count() === 52, 'a rack switch is drawn with its real ports (48 + 4 SFP)');
  await page.click('.cat-crumbs button:has-text("All brands")');
  await page.click('.cat-brand:has-text("Dell")');
  await page.waitForSelector('.cat-model');
  const dellCrumbs = await page.textContent('.cat-crumbs');
  check(await page.locator('.cat-type').count() === 0 && /Dell\s*›\s*Servers/.test(dellCrumbs), `a brand with one type goes straight to its models (${dellCrumbs})`);
  await page.fill('.cat-search input', 'r740');
  check((await page.locator('.cat-model').allTextContents()).every((t) => /R740/.test(t)), 'search narrows to models from any step');
  await page.locator('.cat-model', { hasText: 'PowerEdge R740xd' }).click();
  check(/Redfish/.test(await page.textContent('.cat-chosen')) && await page.locator('.cat-chosen .rack-item').count() === 1, 'a chosen model shows its front, size and how it is read');
  await page.click('.cat-chosen button:text-is("Add this device")');
  await page.waitForSelector('#device-editor:not([hidden])');
  check(await page.inputValue('#device-form input[name=brand]') === 'Dell' && await page.inputValue('#device-form input[name=modelName]') === 'PowerEdge R740xd'
    && await page.inputValue('#device-form input[name=height]') === '2' && await page.inputValue('#device-front') === 'dell14' && await page.inputValue('#device-drives') === '24x2.5'
    && await page.locator('#conn-list .conn-card').count() === 1, 'the catalog fills brand, model, height, front and bays, and adds a Redfish connection');
  await page.fill('#device-form input[name=name]', 'Orion');
  let c = conn(0);
  await fill(c, 'Address', '127.0.0.1:18443');
  await fill(c, 'Username', 'root');
  await fill(c, 'Password', 'calvin');
  await c.locator('button', { hasText: 'Fetch certificate' }).click();
  await c.locator('button', { hasText: 'Use this fingerprint' }).click();
  c = conn(0);
  await c.locator('button', { hasText: 'Test' }).click();
  await c.locator('.conn-result .msg').waitFor();
  const t1 = await c.locator('.conn-result').textContent();
  check(/Connected: PowerEdge R730xd/.test(t1), `iDRAC tested before saving (${t1})`);
  await page.selectOption('#conn-add', 'proxmox');
  c = conn(1);
  await fill(c, 'Address', '127.0.0.1:18443');
  await fill(c, 'API token ID', 'root@pam!dash');
  await fill(c, 'Token secret', '11111111-2222-3333-4444-555555555555');
  await c.locator('button', { hasText: 'Fetch certificate' }).click();
  await c.locator('button', { hasText: 'Use this fingerprint' }).click();
  c = conn(1);
  await c.locator('button', { hasText: 'Test' }).click();
  await page.waitForFunction(() => document.querySelectorAll('#conn-list .conn-card')[1]?.querySelectorAll('select option').length >= 4);
  c = conn(1);
  const nodeSelect = c.locator('label', { hasText: 'Node' }).locator('select');
  check((await nodeSelect.locator('option').allTextContents()).join('|').includes('pve1|pve2'), 'Proxmox test fills the node list');
  await nodeSelect.selectOption('pve1');
  check(await conn(0).locator('input[type=password]').first().inputValue() === 'calvin', 'typed iDRAC password kept while editing other connections');
  await page.screenshot({ path: `${S}/ui5-editor.png`, fullPage: true });
  await page.click('#device-save');
  await page.waitForSelector('#device-editor[hidden]', { state: 'attached' });
  const row = page.locator('#device-list .device-row', { hasText: 'Orion' });
  check((await row.textContent()).includes('Redfish + Proxmox'), `device list: ${await row.locator('.device-links').textContent()}`);

  // re-open: secrets are not shown, only "Stored"
  await row.click();
  const ph = await conn(0).locator('input[type=password]').first().getAttribute('placeholder');
  const val = await conn(0).locator('input[type=password]').first().inputValue();
  check(ph.startsWith('Stored') && val === '', 'saved secret is write-only in the editor');
  check(/Orion/.test(await page.textContent('#device-editor-title')), 'edit opens with the device');
  await page.click('#device-cancel');

  // --- UDM Pro with a UniFi connection, without the catalog; switch + AP appear by themselves ---
  await page.click('#device-new');
  await page.click('dialog.drawer button:has-text("Any other device")');
  await page.waitForSelector('#device-editor:not([hidden])');
  await page.fill('#device-form input[name=name]', 'UDM Pro');
  await page.selectOption('#conn-add', 'unifi');
  check(await page.inputValue('#device-kind') === 'gateway', 'adding a UniFi connection sets the type to gateway');
  c = conn(0);
  await fill(c, 'Address', '127.0.0.1:18443');
  await fill(c, 'Local account', 'viewer');
  await fill(c, 'Password', 'unifipass');
  await c.locator('button', { hasText: 'Fetch certificate' }).click();
  await c.locator('button', { hasText: 'Use this fingerprint' }).click();
  await page.fill('#device-form input[name=u]', '24');
  await page.click('#device-save');
  await page.waitForTimeout(2500);
  await page.click('#tabbtn-power');
  await page.click('#tabbtn-devices');
  await page.waitForTimeout(800);
  const listText = await page.textContent('#device-list');
  check(/USW-24-POE Rack/.test(listText) && /U7 Pro Hallway/.test(listText), 'switch and AP appeared automatically');
  check(/Not placed \(1\)/.test(listText) && /Outside the rack \(3\)/.test(listText) && /Driveway/.test(listText), 'switch is "not placed"; AP and Protect cameras are "outside the rack"');
  await page.screenshot({ path: `${S}/ui5-devices.png`, fullPage: true });

  // --- Home: one tile per device; its drawer has a section per connection ---
  await page.goto(B + '/');
  await page.waitForSelector('#devices .dtile');
  await page.waitForTimeout(800);
  const tiles = await page.$$eval('#devices .dtile .tile-name', (n) => n.map((x) => x.textContent));
  console.log('  tiles:', JSON.stringify(tiles));
  await page.locator('#devices .dtile', { hasText: 'Orion' }).click();
  await page.waitForSelector('dialog.drawer[open] .section-title');
  const sections = await page.$$eval('dialog.drawer .section-title', (n) => n.map((x) => x.textContent));
  check(tiles.filter((t) => t === 'Orion').length === 1 && sections.includes('Hardware · iDRAC') && sections.includes('Proxmox · node pve1'), `Orion: one tile; its drawer has the iDRAC and Proxmox sections (${sections.join(', ')})`);
  check(/Dell PowerEdge R740xd|PowerEdge R730xd/.test(await page.textContent('dialog.drawer .d-head p')), 'the drawer names the model');
  const odinText = await page.textContent('dialog.drawer');
  await page.keyboard.press('Escape');
  check(odinText.includes('pve1') && !odinText.includes('pve2') && /VMs and containers · \d+ of \d+ running/.test(odinText) && odinText.includes('All VMs, with their disks and backups'), 'Orion shows its own node and its guests, with a link to the VMs page');
  const vmPage = await page.context().newPage();
  await vmPage.goto(B + '/vms');
  await vmPage.waitForSelector('#vm-list .vm-row');
  const vms = await vmPage.$$eval('#vm-list .vm-row strong', (n) => n.map((x) => x.textContent));
  check(vms.includes('truenas') && !vms.includes('tmpl'), `the VMs page lists the VMs and containers (${vms.join(', ')})`);
  await vmPage.click('#vm-filter button:has-text("Stopped")');
  const stopped = await vmPage.$$eval('#vm-list .vm-row strong', (n) => n.map((x) => x.textContent));
  check(stopped.length >= 1 && !stopped.includes('truenas'), `filter: stopped ones (${stopped.join(', ')})`);
  await vmPage.click('#vm-filter button:has-text("All")');
  await vmPage.fill('#vm-q', '192.168.1.50');
  const found = await vmPage.$$eval('#vm-list .vm-row strong', (n) => n.map((x) => x.textContent));
  check(found.join() === 'truenas', `search by address (${found.join(', ')})`);
  await vmPage.click('#vm-list .vm-row');
  await vmPage.waitForSelector('dialog.drawer[open] .vm-detail h3');
  const detail = await vmPage.textContent('dialog.drawer');
  check(/Debian GNU\/Linux 12/.test(detail) && /\/srv\/data/.test(detail) && /Backups kept/.test(detail) && /Open in Proxmox/.test(detail) && /#100%3A|#[0-9a-f-]+%3A100/.test(vmPage.url()), `a VM opens with its OS, disks, backups and a link into Proxmox; the address names it (${[/Debian GNU\/Linux 12/.test(detail), /\/srv\/data/.test(detail), /Backups kept/.test(detail), /Open in Proxmox/.test(detail), vmPage.url()].join(' ')})`);
  await vmPage.screenshot({ path: `${S}/vms-page.png`, fullPage: true });
  await vmPage.close();
  await page.locator('#devices .dtile', { hasText: 'UDM Pro' }).click();
  await page.waitForSelector('dialog.drawer[open] .section-title');
  const udmSecs = await page.$$eval('dialog.drawer .section-title', (n) => n.map((x) => x.textContent));
  check(udmSecs.includes('Network · UniFi') && udmSecs.some((x) => /UniFi · UDMPRO/.test(x)), `UDM Pro: network overview + its own gateway section (${udmSecs.join(', ')})`);
  await page.keyboard.press('Escape');
  check(tiles.includes('USW-24-POE Rack'), 'switch gets its own tile');
  await page.goto(B + '/#rack');
  await page.waitForSelector('#rack-view .rack-item.kind-server');
  await page.click('.rack-item.kind-server');
  await page.waitForFunction(() => document.querySelector('.rack-detail h2')?.textContent === 'Orion');
  check(true, 'clicking Orion in the rack shows Orion beside the rack');
  await page.goto(B + '/');
  await page.waitForSelector('#devices .dtile');
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: `${S}/ui5-dashboard.png` });

  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(B + '/admin#devices');
  await page.waitForSelector('#device-list .device-row');
  check((await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)) <= 0, 'admin has no horizontal overflow on phone');
  console.log(problems.length ? '\nPROBLEMS:\n' + problems.join('\n') : '\nUI OK: no console/CSP errors');
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
